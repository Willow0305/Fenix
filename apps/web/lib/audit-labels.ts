/** Ação em português; sem tradução, monta "Área: verbo" a partir do código. */
export function auditActionLabel(action: string): string {
  const known = AUDIT_ACTION_LABELS[action];

  if (known) {
    return known;
  }

  const parts = action.split('.');
  const area = AREA_LABELS[parts[0] ?? ''];
  const verb = VERB_LABELS[parts[parts.length - 1] ?? ''];

  return area && verb ? `${area}: ${verb}` : action;
}

export function auditEntityLabel(entityType: string): string {
  return AUDIT_ENTITY_LABELS[entityType] ?? entityType;
}

/** Ações conhecidas em ordem alfabética do texto, para o filtro. */
export function auditActionOptions(): { value: string; label: string }[] {
  return Object.entries(AUDIT_ACTION_LABELS)
    .map(([value, label]) => ({ value, label }))
    .sort((a, b) => a.label.localeCompare(b.label, 'pt-BR'));
}
